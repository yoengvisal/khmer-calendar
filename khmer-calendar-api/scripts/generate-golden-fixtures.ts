/**
 * Regenerates shared/fixtures/khmer-lunar-golden.json from the TypeScript lunar engine.
 * The Dart engine in the mobile app is tested against this file for parity.
 * Run: npm run fixtures:golden   (only after an intentional algorithm change)
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  addDays,
  formatIsoDate,
  type CivilDate,
} from '../src/modules/lunar/domain/civil-date.js';
import { KhmerLunarCalendar } from '../src/modules/lunar/domain/khmer-lunar-calendar.js';

const cal = new KhmerLunarCalendar();
const rows = new Map<string, (string | number | boolean)[]>();
const add = (date: CivilDate) => {
  const iso = formatIsoDate(date);
  if (rows.has(iso)) return;
  const l = cal.toLunar(date);
  rows.set(iso, [
    iso,
    l.day,
    l.moonPhase,
    l.monthIndex,
    l.beYear,
    l.jsYear,
    l.animalYear,
    l.sak,
    l.dayOfWeek,
    l.isHolyDay ? 1 : 0,
  ]);
};
for (
  let d: CivilDate = { year: 2020, month: 1, day: 1 };
  d.year <= 2032;
  d = addDays(d, 1)
)
  add(d);
for (
  let d: CivilDate = { year: 1900, month: 1, day: 1 };
  d.year <= 2100;
  d = addDays(d, 17)
)
  add(d);

const newYears = [];
for (let y = 1900; y <= 2100; y++) {
  const n = cal.newYear(y);
  newYears.push([
    y,
    formatIsoDate(n.mohaSongkran),
    n.hour,
    n.minute,
    formatIsoDate(n.lerngSak),
    n.numberOfDays,
  ]);
}

const out = resolve(
  import.meta.dirname,
  '../../shared/fixtures/khmer-lunar-golden.json',
);
writeFileSync(
  out,
  JSON.stringify({
    description:
      'Golden vectors for the Khmer lunar engine. Generated by khmer-calendar-api/scripts/generate-golden-fixtures.ts',
    dayFields: [
      'date',
      'lunarDay',
      'moonPhase',
      'monthIndex',
      'beYear',
      'jsYear',
      'animalYear',
      'sak',
      'dayOfWeek',
      'isHolyDay',
    ],
    newYearFields: [
      'gregorianYear',
      'mohaSongkran',
      'hour',
      'minute',
      'lerngSak',
      'numberOfDays',
    ],
    days: [...rows.values()].sort((a, b) =>
      String(a[0]).localeCompare(String(b[0])),
    ),
    newYears,
  }) + '\n',
);
console.log(
  `wrote ${rows.size} day vectors and ${newYears.length} new-year vectors to ${out}`,
);
